"""Telugu inference script.

Generates speech and variance-adaptor analysis plots for 5 Telugu test sentences
using the trained FastSpeech 2 model.

Test sentences (chosen to test specific linguistic phenomena):
  T1: Long compound word — "న్యూరోఫార్మకోలాజికల్" (neuropharmacological)
  T2a/T2b: Polysemy — "పట్టు" meaning "grip" (noun) vs. "silk" (noun in compound)
  T3: Short simple sentence — forest scene
  T4: Mixed content — digits, time (10:45), ordinal (12వ), date in Telugu

Outputs per sentence (saved to --out directory):
  test_generated_audios/<ID>.wav              — synthesised speech
  test_generated_audios/<ID>_phonemes.txt     — grapheme sequence used
  variance_adaptor_plots/duration/<ID>_duration.png  — duration bar chart
  variance_adaptor_plots/pitch/<ID>_pitch.png        — pitch F0 line plot
  variance_adaptor_plots/energy/<ID>_energy.png      — energy line plot
  variance_adaptor_plots/csv/<ID>_variance.csv       — numeric data

Changes vs. the original ming024 synthesize.py:
  - Telugu grapheme-level text front-end (no phoneme dictionary).
  - Telugu-specific text normalisation: digits → Telugu words, time/ordinals.
  - Finds and uses an installed Telugu font for plot axis labels.
  - Saves phoneme/grapheme sequences to text files for reference.

Usage (from the repo root):
    python Telugu/inference.py \\
        --restore_step 10000 \\
        -p Telugu/config.yaml \\
        -m Telugu/config.yaml \\
        -t Telugu/config.yaml \\
        --out Results/Telugu

Prerequisites:
  - Trained checkpoint at <ckpt_path>/<restore_step>.pth.tar
  - HiFi-GAN universal vocoder at hifigan/generator_universal.pth.tar
  - Preprocessed data at <preprocessed_path> (for stats.json + speakers.json)
  - text/telugu_symbols.json (generated by Telugu/preprocess.py)
  - Optionally: a Telugu font installed (e.g. fonts-telu on Ubuntu/Colab)
"""
import argparse
import json
import os
import sys

import torch
import yaml

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import tts_helpers as h
from utils.model import get_model, get_vocoder

# ---------------------------------------------------------------------------
# 5 test sentences (preserving text exactly as given in the assignment)
# ---------------------------------------------------------------------------
TEST = {
    "T1": "న్యూరోఫార్మకోలాజికల్ పరిశోధనలో నూతన ఔషధాల ప్రభావాన్ని విశ్లేషించారు.",
    "T2a": "తాడుపై అతని పట్టు చాలా బలంగా ఉంది.",
    "T2b": "ఆమె పట్టుచీరను ధరించి వేడుకకు వచ్చింది.",
    "T3": "పులి అడవిలో నిశ్శబ్దంగా నడిచింది.",
    "T4": "ఈ సమావేశం 2026 నవంబర్ 12వ తేదీ ఉదయం 10:45 గంటలకు "
          "ప్రారంభమవుతుంది, సమయానికి సిద్ధంగా ఉంచండి.",
}


def _load_section(path, section):
    cfg = yaml.safe_load(open(path, encoding="utf-8"))
    return cfg[section] if section in cfg else cfg


def main():
    ap = argparse.ArgumentParser(
        description="Run Telugu FastSpeech 2 inference and generate variance analysis plots."
    )
    ap.add_argument("--restore_step", type=int, required=True,
                    help="Checkpoint step to load (e.g. 10000).")
    ap.add_argument("-p", "--preprocess_config", type=str,
                    default=os.path.join(os.path.dirname(__file__), "config.yaml"))
    ap.add_argument("-m", "--model_config", type=str,
                    default=os.path.join(os.path.dirname(__file__), "config.yaml"))
    ap.add_argument("-t", "--train_config", type=str,
                    default=os.path.join(os.path.dirname(__file__), "config.yaml"))
    ap.add_argument("--out", type=str, default="Results/Telugu",
                    help="Output directory for WAV files and plots.")
    args = ap.parse_args()

    pc = _load_section(args.preprocess_config, "preprocess")
    mc = _load_section(args.model_config, "model")
    tc = _load_section(args.train_config, "train")
    configs = (pc, mc, tc)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"Device: {device}")

    model = get_model(args, configs, device, train=False)
    vocoder = get_vocoder(mc, device)

    # Load the Telugu symbol set (built by Telugu/preprocess.py).
    _sym_path = os.path.join(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
        "text", "telugu_symbols.json",
    )
    symbols = set(json.load(open(_sym_path, encoding="utf-8")))
    print(f"Telugu symbols loaded: {len(symbols)}")

    font = h.find_telugu_font()
    print(f"Telugu font for plots: {font or '(none found — using index labels)'}")

    wav_dir = os.path.join(args.out, "test_generated_audios")
    plot_dir = os.path.join(args.out, "variance_adaptor_plots")

    for name, text in TEST.items():
        ph = h.te_phonemes(text, symbols)
        normalised = h.normalize_te(text)
        print(f"\n{name} | {text}")
        print(f"      Normalised: {normalised}")
        print(f"      Graphemes:  {ph}")

        h.synthesize_and_plot(
            ph, name, text, 0,  # speaker_id=0 (single-speaker model)
            model, vocoder, configs, device,
            wav_dir, plot_dir, font=font,
        )
        # Save grapheme sequence for reference
        ph_file = os.path.join(wav_dir, f"{name}_phonemes.txt")
        os.makedirs(wav_dir, exist_ok=True)
        open(ph_file, "w", encoding="utf-8").write(ph)
        print(f"      Saved: {wav_dir}/{name}.wav + plots")

    print(f"\nAll outputs written to: {args.out}")


if __name__ == "__main__":
    main()
